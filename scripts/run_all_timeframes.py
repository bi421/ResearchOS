import sys

sys.path.append("cpp_quant/python")
from cpp_quant import CppQuant
import pandas as pd
import glob

print("=" * 60)
print("?? ??? ?????? ??????? ??????? ?????????")
print("=" * 60)

# 1. CSV ????????? ?????
print("\n?? CSV ????????? ????? ?????...")
all_dfs = []
for f in glob.glob("data/raw/histdata/xauusd/DAT_ASCII_XAUUSD_M1_*.csv"):
    df = pd.read_csv(
        f,
        sep=";",
        header=None,
        names=["datetime", "open", "high", "low", "close", "volume"],
        dtype={"datetime": str},
    )
    df["datetime"] = pd.to_datetime(df["datetime"], format="%Y%m%d %H%M%S", errors="coerce")
    df = df.dropna(subset=["datetime"])
    df.set_index("datetime", inplace=True)
    all_dfs.append(df)

df = pd.concat(all_dfs).sort_index()
print(f"? ???? {len(df):,} ?????? 1 ??????? candle")
print(f"   ?? {df.index[0]} ? {df.index[-1]}")

# 2. ?????? ???????? ????????
timeframes = [
    ("1min", "1min", 1),
    ("5min", "5min", 5),
    ("15min", "15min", 15),
    ("30min", "30min", 30),
    ("1h", "1h", 60),
    ("4h", "4h", 240),
    ("1D", "1D", 1440),
    ("W", "W", 10080),
    ("M", "M", 43200),
]

results = []

print("\n" + "=" * 60)
print("?? ??????? ?? ???")
print("=" * 60)

for label, rule, minutes in timeframes:
    print(f"\n? {label} ?????????? ?????...")

    # ??????????
    df_resampled = (
        df.resample(rule)
        .agg({"open": "first", "high": "max", "low": "min", "close": "last", "volume": "sum"})
        .dropna()
    )

    print(f"   ? {len(df_resampled):,} candle")

    # C++ engine ??? ?????????
    engine = CppQuant()
    engine.load_from_dataframe(df_resampled)

    # SMA 20/50 ???????
    result = engine.run_sma(20, 50)

    # ????????
    results.append(
        {
            "timeframe": label,
            "candles": len(df_resampled),
            "trades": result["num_trades"],
            "winrate": result["winrate"],
            "total_return": result["total_return"],
            "sharpe": result["sharpe_ratio"],
            "avg_win": result["avg_win"],
            "avg_loss": result["avg_loss"],
            "profit_factor": result["profit_factor"],
        }
    )

    print(f"   ?? ???????: {result['num_trades']}")
    print(f"   ?? Winrate: {result['winrate']:.2f}%")
    print(f"   ?? ???? ?????: {result['total_return']:.2f}%")
    print(f"   ?? Sharpe: {result['sharpe_ratio']:.2f}")

# 3. ?? ??????? ???????
